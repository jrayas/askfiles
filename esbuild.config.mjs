import esbuild from "esbuild";
import process from "node:process";
import { builtinModules } from "node:module";
import fs from "node:fs";
import path from "node:path";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === "production";

const syncToDevVaultPlugin = {
	name: "sync-to-dev-vault",
	setup(build) {
		build.onEnd((result) => {
			if (result.errors.length > 0) return;
			const targets = [
				path.resolve("dev/testvault/.obsidian/plugins/askfiles"),
				path.resolve("dev/scratch/vault/.obsidian/plugins/askfiles"),
			];
			for (const dir of targets) {
				if (fs.existsSync(dir)) {
					for (const file of ["main.js", "manifest.json", "styles.css"]) {
						if (fs.existsSync(file)) {
							fs.copyFileSync(file, path.join(dir, file));
						}
					}
				}
			}
		});
	},
};

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ["src/main.ts"],
	bundle: true,
	external: [
		"obsidian",
		"electron",
		"@codemirror/autocomplete",
		"@codemirror/collab",
		"@codemirror/commands",
		"@codemirror/language",
		"@codemirror/lint",
		"@codemirror/search",
		"@codemirror/state",
		"@codemirror/view",
		"@lezer/common",
		"@lezer/highlight",
		"@lezer/lr",
		...builtinModules,
	],
	format: "cjs",
	target: "es2021",
	logLevel: "info",
	sourcemap: prod ? false : "inline",
	treeShaking: true,
	outfile: "main.js",
	minify: prod,
	plugins: [syncToDevVaultPlugin],
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
